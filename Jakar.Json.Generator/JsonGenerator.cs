using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;



namespace Jakar.Json.Generator;


/// <summary>
///     Jakar.Json's source generator, for every <see langword="partial"/> type marked <c>[JsonModel]</c>: <c>IJsonSerializable&lt;TSelf&gt;</c> with its <c>ToJson</c> / <c>FromJson</c>
///     helpers (<see cref="Emitter"/>). The code is reflection-free readers and writers generic over <c>IJsonWriter</c> / <c>IJsonReader</c>, plus <c>ISpanFormattable</c> /
///     <c>ISpanParsable</c> (and UTF-8). Settings are resolved at compile time (member → type → <c>[assembly: JsonDefaults]</c> → built-in) and baked into the generated code.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class JsonGenerator : IIncrementalGenerator
{
    internal const string JSON_MODEL_ATTRIBUTE    = "Jakar.Extensions.JsonModelAttribute";
    internal const string JSON_DEFAULTS_ATTRIBUTE = "Jakar.Json.JsonDefaultsAttribute";
    internal const string JSON_MEMBER_ATTRIBUTE   = "Jakar.Json.JsonMemberAttribute";
    internal const string JSON_DERIVED_ATTRIBUTE  = "Jakar.Json.JsonDerivedAttribute";
    internal const string SERIALIZABLE_INTERFACE  = "Jakar.Json.IJsonSerializable`1";
    internal const string CONVERTER_INTERFACE     = "Jakar.Json.IJsonConverter`1";
    internal const string VERSION                 = "10.3.0";


    public void Initialize( IncrementalGeneratorInitializationContext context )
    {
        IncrementalValuesProvider<ModelInfo> models = context.SyntaxProvider.ForAttributeWithMetadataName(JSON_MODEL_ATTRIBUTE, static ( node, _ ) => node is TypeDeclarationSyntax, static ( ctx, token ) => ModelExtractor.Extract(ctx, token));

        IncrementalValueProvider<Settings> defaults = context.CompilationProvider.Select(static ( compilation, _ ) => Settings.BuiltIn.With(Settings.From(compilation.Assembly.GetAttributes().FirstOrDefault(static a => a.AttributeClass is not null && TypeShapes.MetadataName(a.AttributeClass) == JSON_DEFAULTS_ATTRIBUTE))));

        IncrementalValuesProvider<(ModelInfo Model, Settings Defaults)> inputs = models.Combine(defaults);

        context.RegisterSourceOutput(inputs, static ( spc, input ) => Emitter.EmitModel(spc, input.Model, input.Defaults)); // reports the diagnostics, errors included

        // One converter per (enum, naming policy) used anywhere in the assembly.
        IncrementalValueProvider<ImmutableArray<EnumInfo>> enums = inputs.SelectMany(static ( input, _ ) => input.Model.IsFatal
                                                                                                               ? []
                                                                                                               : Emitter.EnumsUsed(input.Model, input.Defaults)).Collect();

        context.RegisterSourceOutput(enums, static ( spc, all ) => EnumEmitter.Emit(spc, all));

        // JsonCodecRegistry entries for every [JsonModel] type, so frameworks that only know a Type (ASP.NET Core formatters) find its codec.
        IncrementalValueProvider<ImmutableArray<string>> codecs = inputs.Select(static ( input, _ ) => input.Model.Registrable && Emitter.CanEmit(input.Model, input.Defaults, out string? _)
                                                                                                           ? input.Model.FullyQualifiedName
                                                                                                           : null).Where(static name => name is not null).Select(static ( name, _ ) => name!).Collect();

        context.RegisterSourceOutput(codecs, static ( spc, names ) => EmitCodecRegistrations(spc, names));
    }


    private static void EmitCodecRegistrations( SourceProductionContext spc, ImmutableArray<string> names )
    {
        if ( names.IsDefaultOrEmpty ) { return; }

        StringBuilder builder = new();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CA2255 // ModuleInitializer in a library: registers each [JsonModel] type's codec (one small object per type), no other side effects");
        builder.AppendLine();
        builder.AppendLine("namespace Jakar.Json.Generated");
        builder.AppendLine("{");
        builder.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCode(\"Jakar.Json.Generator\", \"{VERSION}\")]");
        builder.AppendLine("    internal static class JsonCodecRegistrations");
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void Register()");
        builder.AppendLine("        {");

        foreach ( string name in names.Distinct().OrderBy(static name => name, StringComparer.Ordinal) ) { builder.AppendLine($"            global::Jakar.Json.JsonCodecRegistry.Register<{name}>();"); }

        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        spc.AddSource("JsonCodecRegistrations.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }
}
